// reserved attribute names a spec property may not map onto: the resource's
// own attributes and Terraform's meta-arguments. Kept in step with
// internal/provider reservedAttrs; a test there checks generated kinds.
var reserved = map[string]bool{
	"id": true, "name": true, "labels": true, "annotations": true,
	"count": true, "for_each": true, "provider": true, "lifecycle": true,
	"depends_on": true, "provisioner": true, "connection": true,
}

// snake turns a JSON property or kind name into a Terraform name:
// blockMalware -> block_malware, within30Days -> within_30_days,
// QualityGate -> quality_gate, URLPath -> url_path.
func snake(s string) string {
	rs := []rune(s)
	var b strings.Builder
	for i, r := range rs {
		if r == '-' || r == '.' || r == ' ' {
			b.WriteByte('_')
			continue
		}
		if i > 0 {
			prev := rs[i-1]
			var next rune
			if i+1 < len(rs) {
				next = rs[i+1]
			}
			switch {
			case unicode.IsUpper(r) && (unicode.IsLower(prev) || unicode.IsDigit(prev)):
				b.WriteByte('_')
			case unicode.IsUpper(r) && unicode.IsUpper(prev) && unicode.IsLower(next):
				b.WriteByte('_')
			case unicode.IsDigit(r) && unicode.IsLetter(prev):
				b.WriteByte('_')
			case unicode.IsLower(r) && unicode.IsDigit(prev):
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// lowerCamel is a Go identifier prefix for a kind: QualityGate -> qualityGate.
func lowerCamel(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// kindOut is one generated kind.
type kindOut struct {
	Kind, TypeName, Ident string
	Source                []byte
}

type generator struct {
	set *schemaSet
	// version is the config-schemas release the schemas came from, for the
	// generated header.
	version string
}

// generate emits the kindSpec for one kind.
func (g *generator) generate(kind string) (*kindOut, error) {
	root, ok := g.set.files[kind+".schema.json"]
	if !ok {
		return nil, fmt.Errorf("no schema for kind %s", kind)
	}
	meta, _, err := g.set.flatten(root.Properties["metadata"])
	if err != nil || meta == nil {
		return nil, fmt.Errorf("%s: metadata: %v", kind, err)
	}
	singleton := false
	pattern := ""
	if nm, ok := meta.Properties["name"]; ok {
		if nm.Const == "default" {
			singleton = true
		}
		r, _, err := g.set.resolve(nm)
		if err != nil {
			return nil, fmt.Errorf("%s: metadata.name: %w", kind, err)
		}
		pattern = r.Pattern
		if r.Const == "default" {
			singleton = true
		}
	}
	spec, _, err := g.set.flatten(root.Properties["spec"])
	if err != nil {
		return nil, fmt.Errorf("%s: spec: %w", kind, err)
	}
	if spec == nil {
		spec = &node{}
	}

	ident := lowerCamel(kind)
	var attrs, fields bytes.Buffer
	if err := g.object(&attrs, &fields, spec, kind+".spec", true, false); err != nil {
		return nil, err
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by cmd/genresources from config-schemas %s. DO NOT EDIT.\n\n", g.version)
	src.WriteString("package provider\n\n")
	src.WriteString(imports)
	fmt.Fprintf(&src, "// %sKind is the %s config kind.\n", ident, kind)
	fmt.Fprintf(&src, "var %sKind = kindSpec{\n", ident)
	fmt.Fprintf(&src, "Kind: %q,\nTypeName: %q,\n", kind, snake(kind))
	fmt.Fprintf(&src, "Description: %s,\n", strconv.Quote(root.Description))
	fmt.Fprintf(&src, "Singleton: %v,\n", singleton)
	if !singleton && pattern != "" {
		fmt.Fprintf(&src, "NamePattern: %s,\n", strconv.Quote(pattern))
	}
	fmt.Fprintf(&src, "Attributes: func() map[string]schema.Attribute {\nreturn map[string]schema.Attribute{\n%s}\n},\n", attrs.String())
	fmt.Fprintf(&src, "Fields: []field{\n%s},\n}\n", fields.String())
	src.WriteString(keepImports)

	out, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: format generated code: %w\n%s", kind, err, src.String())
	}
	return &kindOut{Kind: kind, TypeName: snake(kind), Ident: ident, Source: out}, nil
}

const imports = `import (
	"regexp"

	"github.com/hashicorp/terraform-plugin-framework-jsontypes/jsontypes"
	"github.com/hashicorp/terraform-plugin-framework-validators/float64validator"
	"github.com/hashicorp/terraform-plugin-framework-validators/int64validator"
	"github.com/hashicorp/terraform-plugin-framework-validators/listvalidator"
	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

`

// keepImports keeps every import used whichever shapes a kind has, so the
// generator never has to track which ones it emitted.
const keepImports = `
var (
	_ = regexp.MustCompile
	_ = jsontypes.NormalizedType{}
	_ = float64validator.AtLeast
	_ = int64validator.AtLeast
	_ = listvalidator.SizeAtLeast
	_ = stringvalidator.OneOf
	_ validator.String
	_ = types.StringType
)
`

// object writes the attributes and fields of an object's properties.
// underList is set inside list or map elements, where a secret cannot be
// write-only: Terraform has no write-only element.
func (g *generator) object(attrs, fields *bytes.Buffer, obj *node, where string, top, underList bool) error {
	names := make([]string, 0, len(obj.Properties))
	for k := range obj.Properties {
		names = append(names, k)
	}
	sort.Strings(names)
	seen := map[string]string{}
	for _, jsonName := range names {
		prop := obj.Properties[jsonName]
		attr := snake(jsonName)
		if top && reserved[attr] {
			return fmt.Errorf("%s.%s: maps to %s, which the resource reserves", where, jsonName, attr)
		}
		if other, dup := seen[attr]; dup {
			return fmt.Errorf("%s: %s and %s both map to %s", where, other, jsonName, attr)
		}
		seen[attr] = jsonName
		if err := g.property(attrs, fields, prop, jsonName, attr, where+"."+jsonName, obj.requires(jsonName), underList); err != nil {
			return err
		}
	}
	return nil
}

func optReq(required bool) string {
	if required {
		return "Required: true,\n"
	}
	return "Optional: true,\n"
}

func (g *generator) property(attrs, fields *bytes.Buffer, prop *node, jsonName, attr, where string, required, underList bool) error {
	secret, err := g.set.isValueFrom(prop)
	if err != nil {
		return fmt.Errorf("%s: %w", where, err)
	}
	r, _, err := g.set.flatten(prop)
	if err != nil {
		return fmt.Errorf("%s: %w", where, err)
	}
	desc := describe(r)

	if secret {
		if underList {
			return fmt.Errorf("%s: a valueFrom secret inside a list or map cannot be write-only", where)
		}
		wo, ver := attr+"_wo", attr+"_wo_version"
		fmt.Fprintf(attrs, "%q: schema.StringAttribute{\nMarkdownDescription: %s,\n%sWriteOnly: true,\nSensitive: true,\n},\n",
			wo, strconv.Quote(strings.TrimSpace(desc+" Write-only: never stored in state. Needs Terraform 1.11 or later. Change `"+ver+"` to send a new value.")), optReq(required))
		fmt.Fprintf(attrs, "%q: schema.Int64Attribute{\nMarkdownDescription: %s,\nOptional: true,\n},\n",
			ver, strconv.Quote("Any number. Change it to send `"+wo+"` again; Terraform cannot see a write-only value change."))
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, WriteOnly: true, Version: %q},\n", wo, jsonName, ver)
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Local: true},\n", ver, jsonName)
		return nil
	}

	head := optReq(required)
	if desc != "" {
		head = fmt.Sprintf("MarkdownDescription: %s,\n", strconv.Quote(desc)) + head
	}
	switch {
	case isObject(r) && len(r.Properties) > 0:
		var ca, cf bytes.Buffer
		if err := g.object(&ca, &cf, r, where, false, underList); err != nil {
			return err
		}
		fmt.Fprintf(attrs, "%q: schema.SingleNestedAttribute{\n%sAttributes: map[string]schema.Attribute{\n%s},\n},\n", attr, head, ca.String())
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldObject, Children: []field{\n%s}},\n", attr, jsonName, cf.String())
		return nil

	case isObject(r) && r.additional() != nil:
		el, _, err := g.set.flatten(r.additional())
		if err != nil {
			return fmt.Errorf("%s: %w", where, err)
		}
		if isObject(el) && len(el.Properties) > 0 {
			var ca, cf bytes.Buffer
			if err := g.object(&ca, &cf, el, where+"{}", false, true); err != nil {
				return err
			}
			fmt.Fprintf(attrs, "%q: schema.MapNestedAttribute{\n%sNestedObject: schema.NestedAttributeObject{Attributes: map[string]schema.Attribute{\n%s}},\n},\n", attr, head, ca.String())
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldMapObject, Children: []field{\n%s}},\n", attr, jsonName, cf.String())
			return nil
		}
		if ek, et, ok := scalar(el); ok {
			fmt.Fprintf(attrs, "%q: schema.MapAttribute{\n%sElementType: %s,\n},\n", attr, head, et)
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldMap, Elem: %s},\n", attr, jsonName, ek)
			return nil
		}

	case r.hasType("array") && r.Items != nil:
		el, _, err := g.set.flatten(r.Items)
		if err != nil {
			return fmt.Errorf("%s: %w", where, err)
		}
		lv := listValidators(r)
		if isObject(el) && len(el.Properties) > 0 {
			var ca, cf bytes.Buffer
			if err := g.object(&ca, &cf, el, where+"[]", false, true); err != nil {
				return err
			}
			fmt.Fprintf(attrs, "%q: schema.ListNestedAttribute{\n%s%sNestedObject: schema.NestedAttributeObject{Attributes: map[string]schema.Attribute{\n%s}},\n},\n", attr, head, lv, ca.String())
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldListObject, Children: []field{\n%s}},\n", attr, jsonName, cf.String())
			return nil
		}
		if ek, et, ok := scalar(el); ok {
			fmt.Fprintf(attrs, "%q: schema.ListAttribute{\n%s%sElementType: %s,\n},\n", attr, head, lv, et)
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldList, Elem: %s},\n", attr, jsonName, ek)
			return nil
		}

	default:
		if ek, _, ok := scalar(r); ok {
			fmt.Fprintf(attrs, "%q: schema.%s{\n%s%s},\n", attr, scalarAttr(ek), head, scalarValidators(r, ek))
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: %s},\n", attr, jsonName, ek)
			return nil
		}
	}

	// Anything HCL cannot type exactly (oneOf of differing shapes, free
	// objects, arrays of arrays) is carried as a JSON string, compared
	// semantically so key order and spacing never show as a diff.
	fmt.Fprintf(attrs, "%q: schema.StringAttribute{\n%sCustomType: jsontypes.NormalizedType{},\n},\n",
		attr, fmt.Sprintf("MarkdownDescription: %s,\n%s", strconv.Quote(strings.TrimSpace(desc+" A JSON-encoded value; use jsonencode().")), optReq(required)))
	fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldJSON},\n", attr, jsonName)
	return nil
}

func isObject(n *node) bool {
	return n.hasType("object") || (len(n.types()) == 0 && len(n.Properties) > 0)
}

// scalar classifies a leaf. Enum and const without a type are strings when
// every value is one.
func scalar(n *node) (kind, elemType string, ok bool) {
	ts := n.types()
	nonNull := []string{}
	for _, t := range ts {
		if t != "null" {
			nonNull = append(nonNull, t)
		}
	}
	if len(nonNull) == 0 && (len(n.Enum) > 0 || n.Const != nil) {
		vals := append([]any{n.Const}, n.Enum...)
		for _, v := range vals {
			if v == nil {
				continue
			}
			if _, isStr := v.(string); !isStr {
				return "", "", false
			}
		}
		nonNull = []string{"string"}
	}
	if len(nonNull) != 1 || len(n.OneOf) > 0 || len(n.AnyOf) > 0 {
		return "", "", false
	}
	switch nonNull[0] {
	case "string":
		return "fieldString", "types.StringType", true
	case "integer":
		return "fieldInt", "types.Int64Type", true
	case "number":
		return "fieldFloat", "types.Float64Type", true
	case "boolean":
		return "fieldBool", "types.BoolType", true
	}
	return "", "", false
}

func scalarAttr(kind string) string {
	switch kind {
	case "fieldInt":
		return "Int64Attribute"
	case "fieldFloat":
		return "Float64Attribute"
	case "fieldBool":
		return "BoolAttribute"
	}
	return "StringAttribute"
}

func scalarValidators(n *node, kind string) string {
	var vs []string
	switch kind {
	case "fieldString":
		vals := []string{}
		if s, ok := n.Const.(string); ok {
			vals = append(vals, strconv.Quote(s))
		}
		for _, e := range n.Enum {
			if s, ok := e.(string); ok {
				vals = append(vals, strconv.Quote(s))
			}
		}
		if len(vals) > 0 {
			vs = append(vs, "stringvalidator.OneOf("+strings.Join(vals, ", ")+")")
		}
		switch {
		case n.MinLength != nil && n.MaxLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthBetween(%d, %d)", *n.MinLength, *n.MaxLength))
		case n.MinLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtLeast(%d)", *n.MinLength))
		case n.MaxLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtMost(%d)", *n.MaxLength))
		}
		// JSON Schema patterns are ECMA-262; only emit the ones RE2 accepts.
		// The server validates the rest.
		if n.Pattern != "" {
			if _, err := regexp.Compile(n.Pattern); err == nil {
				vs = append(vs, fmt.Sprintf("stringvalidator.RegexMatches(regexp.MustCompile(%s), %s)",
					strconv.Quote(n.Pattern), strconv.Quote("must match "+n.Pattern)))
			}
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.String{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	case "fieldInt":
		if n.Minimum != nil {
			vs = append(vs, "int64validator.AtLeast("+n.Minimum.String()+")")
		}
		if n.Maximum != nil {
			vs = append(vs, "int64validator.AtMost("+n.Maximum.String()+")")
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.Int64{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	case "fieldFloat":
		if n.Minimum != nil {
			vs = append(vs, "float64validator.AtLeast("+n.Minimum.String()+")")
		}
		if n.Maximum != nil {
			vs = append(vs, "float64validator.AtMost("+n.Maximum.String()+")")
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.Float64{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	}
	return ""
}

func listValidators(n *node) string {
	var vs []string
	if n.MinItems != nil {
		vs = append(vs, fmt.Sprintf("listvalidator.SizeAtLeast(%d)", *n.MinItems))
	}
	if n.MaxItems != nil {
		vs = append(vs, fmt.Sprintf("listvalidator.SizeAtMost(%d)", *n.MaxItems))
	}
	if len(vs) == 0 {
		return ""
	}
	return "Validators: []validator.List{\n" + strings.Join(vs, ",\n") + ",\n},\n"
}

// describe is the attribute's documentation: the schema description plus
// its allowed values and server default, which tfplugindocs then publishes.
func describe(n *node) string {
	d := strings.TrimSpace(n.Description)
	var vals []string
	for _, e := range n.Enum {
		vals = append(vals, fmt.Sprintf("`%v`", e))
	}
	if len(vals) > 0 {
		d = strings.TrimSpace(d + " One of " + strings.Join(vals, ", ") + ".")
	}
	if n.Default != nil {
		b, _ := json.Marshal(n.Default)
		d = strings.TrimSpace(d + " Schema default: `" + strings.Trim(string(b), `"`) + "`.")
	}
	return d
}

// registry emits the list of every generated kind.
func registry(version, varName string, kinds []*kindOut) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/genresources from config-schemas %s. DO NOT EDIT.\n\n", version)
	b.WriteString("package provider\n\n")
	fmt.Fprintf(&b, "// %s is every kind generated from the schemas, one resource each.\n", varName)
	fmt.Fprintf(&b, "var %s = []kindSpec{\n", varName)
	for _, k := range kinds {
		fmt.Fprintf(&b, "%sKind,\n", k.Ident)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
