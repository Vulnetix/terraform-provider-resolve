// keepImports keeps every import used whichever shapes a kind has, so the
// generator never has to track which ones it emitted.
const keepImports = `
var (
	_ = regexp.MustCompile
	_ = jsontypes.NormalizedType{}
	_ = float64validator.AtLeast
	_ = int64validator.AtLeast
	_ = listvalidator.SizeAtLeast
	_ = setvalidator.SizeAtLeast
	_ = stringvalidator.OneOf
	_ validator.String
	_ = types.StringType
)
`

// object writes the attributes and fields of an object's properties.
// underList is set inside list or map elements, where a secret cannot be
// write-only: Terraform has no write-only element.
func (g *generator) object(attrs, fields *bytes.Buffer, tree *[]hfield, obj *node, where string, top, underList bool) error {
	names := make([]string, 0, len(obj.Properties))
	for k := range obj.Properties {
		names = append(names, k)
	}
	sort.Strings(names)
	seen := map[string]string{}
	for _, jsonName := range names {
		prop := obj.Properties[jsonName]
		if prop.boolean != nil {
			// true allows anything and false forbids the property: neither
			// is an argument.
			continue
		}
		attr := snake(jsonName)
		if r, ok := renames[where+"."+jsonName]; ok && top {
			attr = r
		}
		if top && reserved[attr] {
			return fmt.Errorf("%s.%s: maps to %s, which the resource reserves", where, jsonName, attr)
		}
		if other, dup := seen[attr]; dup {
			return fmt.Errorf("%s: %s and %s both map to %s", where, other, jsonName, attr)
		}
		seen[attr] = jsonName
		if err := g.property(attrs, fields, tree, prop, jsonName, attr, where+"."+jsonName, obj.requires(jsonName), underList); err != nil {
			return err
		}
	}
	return nil
}

func optReq(required bool) string {
	if required {
		return "Required: true,\n"
	}
	return "Optional: true,\n"
}

func (g *generator) property(attrs, fields *bytes.Buffer, tree *[]hfield, prop *node, jsonName, attr, where string, required, underList bool) error {
	secret, err := g.set.isValueFrom(prop)
	if err != nil {
		return fmt.Errorf("%s: %w", where, err)
	}
	r, _, err := g.set.flatten(prop)
	if err != nil {
		return fmt.Errorf("%s: %w", where, err)
	}
	desc := describe(r)
	if env := g.celEnv(where); env != "" {
		desc = strings.TrimSpace(desc + " A CEL expression, evaluated in the `" + env + "` environment.")
	}

	if secret {
		if underList {
			return fmt.Errorf("%s: a valueFrom secret inside a list or map cannot be write-only", where)
		}
		g.secrets = append(g.secrets, docPath(where))
		wo, ver := attr+"_wo", attr+"_wo_version"
		// Always optional, even when the schema requires the secret: the server
		// holds it, and leaving it out keeps that value, so an object that
		// already has one can be imported and planned without it. The server
		// still refuses a create that leaves a required secret out.
		reqNote := ""
		if required {
			reqNote = " Required by the server when the object is created; leave it out afterwards to keep the value it holds."
		}
		fmt.Fprintf(attrs, "%q: schema.StringAttribute{\nMarkdownDescription: %s,\n%sWriteOnly: true,\nSensitive: true,\n},\n",
			wo, strconv.Quote(strings.TrimSpace(desc+" Write-only: never stored in state. Needs Terraform 1.11 or later. Change `"+ver+"` to send a new value."+reqNote)), optReq(false))
		fmt.Fprintf(attrs, "%q: schema.Int64Attribute{\nMarkdownDescription: %s,\nOptional: true,\n},\n",
			ver, strconv.Quote("Any number. Change it to send `"+wo+"` again; Terraform cannot see a write-only value change."))
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, WriteOnly: true, Version: %q},\n", wo, jsonName, ver)
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Local: true},\n", ver, jsonName)
		*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeSecret})
		return nil
	}

	head := optReq(required)
	if desc != "" {
		head = fmt.Sprintf("MarkdownDescription: %s,\n", strconv.Quote(desc)) + head
	}
	switch {
	case isObject(r) && len(r.Properties) > 0:
		var ca, cf bytes.Buffer
		var ct []hfield
		if err := g.object(&ca, &cf, &ct, r, where, false, underList); err != nil {
			return err
		}
		*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeObject, Children: ct})
		fmt.Fprintf(attrs, "%q: schema.SingleNestedAttribute{\n%sAttributes: map[string]schema.Attribute{\n%s},\n},\n", attr, head, ca.String())
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldObject, Children: []field{\n%s}},\n", attr, jsonName, cf.String())
		return nil

	case isObject(r) && r.additional() != nil:
		el, _, err := g.set.flatten(r.additional())
		if err != nil {
			return fmt.Errorf("%s: %w", where, err)
		}
		if isObject(el) && len(el.Properties) > 0 {
			var ca, cf bytes.Buffer
			var ct []hfield
			if err := g.object(&ca, &cf, &ct, el, where+"{}", false, true); err != nil {
				return err
			}
			*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeMapObject, Children: ct})
			fmt.Fprintf(attrs, "%q: schema.MapNestedAttribute{\n%sNestedObject: schema.NestedAttributeObject{Attributes: map[string]schema.Attribute{\n%s}},\n},\n", attr, head, ca.String())
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldMapObject, Children: []field{\n%s}},\n", attr, jsonName, cf.String())
			return nil
		}
		if ek, et, ok := scalar(el); ok {
			fmt.Fprintf(attrs, "%q: schema.MapAttribute{\n%sElementType: %s,\n},\n", attr, head, et)
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldMap, Elem: %s},\n", attr, jsonName, ek)
			*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeMap, Elem: ek})
			return nil
		}

	case r.hasType("array") && r.Items != nil:
		el, _, err := g.set.flatten(r.Items)
		if err != nil {
			return fmt.Errorf("%s: %w", where, err)
		}
		nested := isObject(el) && len(el.Properties) > 0
		ek, et, isScalar := scalar(el)
		if !nested && !isScalar {
			break
		}
		coll, fk := "List", "fieldList"
		if !g.ordered(where, r) {
			coll, fk = "Set", "fieldSet"
		}
		lv := sizeValidators(r, coll)
		if nested {
			var ca, cf bytes.Buffer
			var ct []hfield
			if err := g.object(&ca, &cf, &ct, el, where+"[]", false, true); err != nil {
				return err
			}
			*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeListObject, Children: ct})
			fmt.Fprintf(attrs, "%q: schema.%sNestedAttribute{\n%s%sNestedObject: schema.NestedAttributeObject{Attributes: map[string]schema.Attribute{\n%s}},\n},\n", attr, coll, head, lv, ca.String())
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: %sObject, Children: []field{\n%s}},\n", attr, jsonName, fk, cf.String())
			return nil
		}
		fmt.Fprintf(attrs, "%q: schema.%sAttribute{\n%s%sElementType: %s,\n},\n", attr, coll, head, lv, et)
		fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: %s, Elem: %s},\n", attr, jsonName, fk, ek)
		*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeList, Elem: ek})
		return nil

	default:
		if ek, _, ok := scalar(r); ok {
			if _, ok := sensitive[where]; ok && ek == "fieldString" {
				if g.marked == nil {
					g.marked = map[string]bool{}
				}
				g.marked[where] = true
				head += "Sensitive: true,\n"
			}
			fmt.Fprintf(attrs, "%q: schema.%s{\n%s%s},\n", attr, scalarAttr(ek), head, scalarValidators(r, ek))
			fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: %s%s},\n", attr, jsonName, ek, defaultLiteral(r))
			*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeScalar, Elem: ek})
			return nil
		}
	}

	// Anything HCL cannot type exactly (oneOf of differing shapes, free
	// objects, arrays of arrays) is carried as a JSON string, compared
	// semantically so key order and spacing never show as a diff.
	fmt.Fprintf(attrs, "%q: schema.StringAttribute{\n%sCustomType: jsontypes.NormalizedType{},\n},\n",
		attr, fmt.Sprintf("MarkdownDescription: %s,\n%s", strconv.Quote(strings.TrimSpace(desc+" A JSON-encoded value; use jsonencode().")), optReq(required)))
	fmt.Fprintf(fields, "{Attr: %q, JSON: %q, Kind: fieldJSON},\n", attr, jsonName)
	*tree = append(*tree, hfield{Attr: attr, JSON: jsonName, Shape: shapeJSON})
	return nil
}

func isObject(n *node) bool {
	return n.hasType("object") || (len(n.types()) == 0 && len(n.Properties) > 0)
}

// scalar classifies a leaf. Enum and const without a type take the type
// every value shares (string or boolean). A declared type wins over oneOf and
// anyOf, which then only constrain the value (a timestamp's formats, a
// teaId's patterns). A string that may also be a number (a guardrail
// pattern, "5" or 5) is a string: the schema accepts the string form.
func scalar(n *node) (kind, elemType string, ok bool) {
	ts := n.types()
	nonNull := []string{}
	for _, t := range ts {
		if t != "null" {
			nonNull = append(nonNull, t)
		}
	}
	declared := len(nonNull) > 0
	if !declared && (len(n.Enum) > 0 || n.Const != nil) {
		nonNull = []string{constType(append([]any{n.Const}, n.Enum...))}
	}
	if len(nonNull) == 2 && contains(nonNull, "string") && (contains(nonNull, "integer") || contains(nonNull, "number")) {
		nonNull = []string{"string"}
	}
	if len(nonNull) != 1 || (!declared && (len(n.OneOf) > 0 || len(n.AnyOf) > 0)) {
		return "", "", false
	}
	switch nonNull[0] {
	case "string":
		return "fieldString", "types.StringType", true
	case "integer":
		return "fieldInt", "types.Int64Type", true
	case "number":
		return "fieldFloat", "types.Float64Type", true
	case "boolean":
		return "fieldBool", "types.BoolType", true
	}
	return "", "", false
}

// constType is the JSON type every non-null value shares, or "" when they
// differ or are not strings or booleans.
func constType(vals []any) string {
	t := ""
	for _, v := range vals {
		var vt string
		switch v.(type) {
		case nil:
			continue
		case string:
			vt = "string"
		case bool:
			vt = "boolean"
		default:
			return ""
		}
		if t != "" && t != vt {
			return ""
		}
		t = vt
	}
	return t
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

func scalarAttr(kind string) string {
	switch kind {
	case "fieldInt":
		return "Int64Attribute"
	case "fieldFloat":
		return "Float64Attribute"
	case "fieldBool":
		return "BoolAttribute"
	}
	return "StringAttribute"
}

func scalarValidators(n *node, kind string) string {
	var vs []string
	switch kind {
	case "fieldString":
		vals := []string{}
		if s, ok := n.Const.(string); ok {
			vals = append(vals, strconv.Quote(s))
		}
		for _, e := range n.Enum {
			if s, ok := e.(string); ok {
				vals = append(vals, strconv.Quote(s))
			}
		}
		if len(vals) > 0 {
			vs = append(vs, "stringvalidator.OneOf("+strings.Join(vals, ", ")+")")
		}
		switch {
		case n.MinLength != nil && n.MaxLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthBetween(%d, %d)", *n.MinLength, *n.MaxLength))
		case n.MinLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtLeast(%d)", *n.MinLength))
		case n.MaxLength != nil:
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtMost(%d)", *n.MaxLength))
		}
		// JSON Schema patterns are ECMA-262; only emit the ones RE2 accepts.
		// The server validates the rest.
		if n.Pattern != "" {
			if _, err := regexp.Compile(n.Pattern); err == nil {
				vs = append(vs, fmt.Sprintf("stringvalidator.RegexMatches(regexp.MustCompile(%s), %s)",
					strconv.Quote(n.Pattern), strconv.Quote("must match "+n.Pattern)))
			}
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.String{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	case "fieldInt":
		if n.Minimum != nil {
			vs = append(vs, "int64validator.AtLeast("+n.Minimum.String()+")")
		}
		if n.Maximum != nil {
			vs = append(vs, "int64validator.AtMost("+n.Maximum.String()+")")
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.Int64{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	case "fieldFloat":
		if n.Minimum != nil {
			vs = append(vs, "float64validator.AtLeast("+n.Minimum.String()+")")
		}
		if n.Maximum != nil {
			vs = append(vs, "float64validator.AtMost("+n.Maximum.String()+")")
		}
		if len(vs) == 0 {
			return ""
		}
		return "Validators: []validator.Float64{\n" + strings.Join(vs, ",\n") + ",\n},\n"
	}
	return ""
}

// sizeValidators are minItems and maxItems for a List or a Set.
func sizeValidators(n *node, coll string) string {
	pkg := strings.ToLower(coll) + "validator"
	var vs []string
	// No SizeAtLeast: the server enforces minItems when it applies, and it
	// holds objects with fewer (a LogSource with no datasets), which must still
	// import and plan. maxItems stays a plan-time check.
	if n.MaxItems != nil {
		vs = append(vs, fmt.Sprintf("%s.SizeAtMost(%d)", pkg, *n.MaxItems))
	}
	if len(vs) == 0 {
		return ""
	}
	return "Validators: []validator." + coll + "{\n" + strings.Join(vs, ",\n") + ",\n},\n"
}

// defaultLiteral is the field's schema default as a Default argument of the
// field literal, the default JSON-encoded, or nothing when the schema has no
// scalar default. The provider uses it on import (convert.go, fromSpec).
func defaultLiteral(n *node) string {
	if n.Default == nil {
		return ""
	}
	switch n.Default.(type) {
	case string, bool, float64, int, int64, json.Number:
	default:
		return ""
	}
	b, err := json.Marshal(n.Default)
	if err != nil {
		return ""
	}
	return fmt.Sprintf(", Default: %q", string(b))
}

// describe is the attribute's documentation: the schema description plus
// its allowed values and server default, which tfplugindocs then publishes.
func describe(n *node) string {
	d := strings.TrimSpace(n.Description)
	var vals []string
	for _, e := range n.Enum {
		vals = append(vals, fmt.Sprintf("`%v`", e))
	}
	if len(vals) > 0 {
		d = strings.TrimSpace(d + " One of " + strings.Join(vals, ", ") + ".")
	}
	if n.Default != nil {
		b, _ := json.Marshal(n.Default)
		d = strings.TrimSpace(d + " Schema default: `" + strings.Trim(string(b), `"`) + "`.")
	}
	return d
}

// registry emits the list of every generated kind.
func registry(version, varName string, kinds []*kindOut) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/genresources from config-schemas %s. DO NOT EDIT.\n\n", version)
	b.WriteString("package provider\n\n")
	fmt.Fprintf(&b, "// %s is every generated kind the config engine applies, one resource\n// each.\n", varName)
	fmt.Fprintf(&b, "var %s = []kindSpec{\n", varName)
	for _, k := range kinds {
		if k.Served {
			fmt.Fprintf(&b, "%sKind,\n", k.Ident)
		}
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// %sUnserved have a released schema but no engine adapter yet. The\n// provider does not offer them; the tests still exercise them.\n", varName)
	fmt.Fprintf(&b, "var %sUnserved = []kindSpec{\n", varName)
	for _, k := range kinds {
		if !k.Served {
			fmt.Fprintf(&b, "%sKind,\n", k.Ident)
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// docPath turns a generator location (Kind.spec.auth.token, with [] and {}
// marking list elements and map values) into the dotted document path
// x-vulnetix uses (spec.auth.token).
func docPath(where string) string {
	_, p, _ := strings.Cut(where, ".")
	return strings.NewReplacer("[]", "", "{}", "").Replace(p)
}

// celEnv is the CEL environment x-vulnetix.celFields gives the property at
// where, or "" when it is not a CEL expression.
func (g *generator) celEnv(where string) string {
	if g.ann == nil {
		return ""
	}
	p := docPath(where)
	for _, c := range g.ann.CelFields {
		if strings.NewReplacer("[]", "", "[*]", "", "{}", "").Replace(c.Path) == p {
			return c.Env
		}
	}
	return ""
}

// checkSecrets compares the valueFrom fields found in the schema with
// x-vulnetix.secrets: a secret the annotation names but the generator would
// put in state, or the other way round, is refused.
func (g *generator) checkSecrets() error {
	if g.ann == nil {
		return nil
	}
	found := map[string]bool{}
	for _, s := range g.secrets {
		found[s] = true
	}
	for _, s := range g.ann.Secrets {
		p := strings.NewReplacer("[]", "", "[*]", "", "{}", "").Replace(s)
		if !found[p] {
			return fmt.Errorf("%s: x-vulnetix.secrets names %s, which is not a valueFrom field", g.kind, s)
		}
		delete(found, p)
	}
	for s := range found {
		return fmt.Errorf("%s: %s is a valueFrom field missing from x-vulnetix.secrets", g.kind, s)
	}
	return nil
}
